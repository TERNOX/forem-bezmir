# Fork-only: validates and stores a user's ballot for a voting, replacing any
# previous answers. Input shape (category ids as keys, from JSON):
#
#   { "12" => { "nominee_ids" => [5, 9], "other" => "My own pick" }, ... }
#
# For ranked categories nominee_ids is in place order (first = 1st place).
module Votings
  class BallotSubmitter
    # changed: false when an already submitted ballot was re-sent unchanged
    # (no share image regeneration needed).
    Result = Struct.new(:ballot, :errors, :changed, keyword_init: true) do
      def success?
        errors.empty?
      end
    end

    CHOICE_KEYS = %i[voting_category_id voting_nominee_id rank other_text].freeze
    def self.call(...)
      new(...).call
    end

    def initialize(voting:, user:, selections:)
      @voting = voting
      @user = user
      @selections = normalize(selections)
      @errors = {}
    end

    def call
      eligibility = Votings::Eligibility.call(voting, user)
      return Result.new(ballot: nil, errors: { base: [eligibility.reason] }) unless eligibility.eligible?

      categories = voting.categories.includes(:nominees).to_a
      choices = categories.flat_map { |category| build_choices(category) }
      @errors[:base] = [:empty] if choices.empty? && @errors.empty?
      return Result.new(ballot: nil, errors: @errors) if @errors.any?

      ballot, changed = persist(choices)
      Result.new(ballot: ballot, errors: {}, changed: changed)
    end

    private

    attr_reader :voting, :user, :selections

    def normalize(raw)
      raw = raw.to_unsafe_h if raw.respond_to?(:to_unsafe_h)
      return {} unless raw.is_a?(Hash)

      raw.each_with_object({}) do |(category_id, value), acc|
        value = value.to_unsafe_h if value.respond_to?(:to_unsafe_h)
        next unless value.is_a?(Hash)

        value = value.stringify_keys
        acc[category_id.to_s] = {
          nominee_ids: Array(value["nominee_ids"]).map(&:to_i).uniq,
          other: value["other"].to_s.strip.presence
        }
      end
    end

    def build_choices(category)
      selection = selections[category.id.to_s] || { nominee_ids: [], other: nil }
      nominee_ids = selection[:nominee_ids]
      other = category.allow_other? ? selection[:other] : nil

      add_error(category, :unknown_nominee) if (nominee_ids - category.nominees.map(&:id)).any?
      add_error(category, :too_many) if nominee_ids.size + (other ? 1 : 0) > category.max_choices
      add_error(category, :required) if category.required? && nominee_ids.empty? && other.nil?
      add_error(category, :other_too_long) if other && other.length > VotingCategory::OTHER_TEXT_MAX_LENGTH
      return [] if @errors[category.id]

      choices = nominee_ids.each_with_index.map do |nominee_id, index|
        { voting_category_id: category.id, voting_nominee_id: nominee_id,
          rank: category.ranked? ? index + 1 : nil, other_text: nil }
      end
      choices << { voting_category_id: category.id, voting_nominee_id: nil, rank: nil, other_text: other } if other
      choices
    end

    def add_error(category, code)
      (@errors[category.id] ||= []) << code
    end

    def persist(choices)
      attempts = 0
      begin
        VotingBallot.transaction do
          ballot = VotingBallot.find_or_create_by!(voting: voting, user: user)
          ballot.lock!
          next [ballot, false] if ballot.submitted? && same_choices?(ballot, choices)

          ballot.choices.delete_all
          now = Time.current
          VotingChoice.insert_all!(choices.map do |c|
                                     c.merge(voting_ballot_id: ballot.id, created_at: now, updated_at: now)
                                   end)
          ballot.remove_share_image! if ballot.share_image.present? # picks changed; regenerated by a worker
          ballot.update!(submitted_at: now)
          ballot.choices.reset # delete_all left an empty cached target
          [ballot, true]
        end
      rescue ActiveRecord::RecordNotUnique
        attempts += 1
        retry if attempts < 3
        raise
      end
    end

    def same_choices?(ballot, choices)
      existing = ballot.choices.map { |choice| CHOICE_KEYS.map { |key| choice.public_send(key) } }
      incoming = choices.map { |choice| choice.values_at(*CHOICE_KEYS) }
      existing.sort_by(&:to_s) == incoming.sort_by(&:to_s)
    end
  end
end
